#!/usr/bin/env node

import { createHash } from "node:crypto";
import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

import prettier from "prettier";
import sharp from "sharp";

const repositoryRoot = path.resolve(
  path.dirname(fileURLToPath(import.meta.url)),
  "..",
);
const sourcePath = path.join(repositoryRoot, "Ressourcen", "Flash-n-Flip.svg");
const checkOnly = process.argv.includes("--check");

const forbiddenMarkup = [
  /<!ENTITY/i,
  /<(?:script|foreignObject|iframe|object|embed|image|use|style|a)\b/i,
  /\bon[a-z]+\s*=/i,
  /\b(?:href|xlink:href)\s*=/i,
  /\burl\s*\(/i,
  /\b(?:javascript|data|file)\s*:/i,
  /@import/i,
];
const allowedElements = new Set(["svg", "g", "rect", "path"]);

function rgbToHex(red, green, blue) {
  return `#${[red, green, blue]
    .map((channel) => Number(channel).toString(16).padStart(2, "0"))
    .join("")
    .toUpperCase()}`;
}

function mixHex(foreground, foregroundPercent, background) {
  const channels = (hex) =>
    hex
      .slice(1)
      .match(/.{2}/g)
      .map((channel) => Number.parseInt(channel, 16));
  const foregroundChannels = channels(foreground);
  const backgroundChannels = channels(background);
  const ratio = foregroundPercent / 100;
  return rgbToHex(
    ...foregroundChannels.map((channel, index) =>
      Math.round(channel * ratio + backgroundChannels[index] * (1 - ratio)),
    ),
  );
}

export function sanitizeBrandSvg(source) {
  if (Buffer.byteLength(source, "utf8") > 1_000_000) {
    throw new Error("Brand SVG exceeds the 1 MB safety limit.");
  }
  for (const pattern of forbiddenMarkup) {
    if (pattern.test(source)) {
      throw new Error(`Brand SVG contains forbidden markup: ${pattern}`);
    }
  }

  let sanitized = source
    .replace(/<\?xml[\s\S]*?\?>/gi, "")
    .replace(/<!DOCTYPE[\s\S]*?>/gi, "")
    .replace(
      /<svg\b[^>]*>/i,
      '<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 588 588">',
    )
    .trim();

  const elements = [...sanitized.matchAll(/<\/?([a-z][\w:-]*)\b/gi)].map(
    (match) => match[1],
  );
  const unsupported = elements.find((element) => !allowedElements.has(element));
  if (unsupported) {
    throw new Error(`Brand SVG contains unsupported element: ${unsupported}`);
  }
  if (!sanitized.startsWith("<svg ") || !sanitized.endsWith("</svg>")) {
    throw new Error("Brand SVG must contain one complete SVG document.");
  }
  return sanitized;
}

export function extractBrandColors(svg) {
  const background = svg.match(
    /<rect\b[^>]*\bstyle="[^"]*\bfill:\s*rgb\(\s*(\d+)\s*,\s*(\d+)\s*,\s*(\d+)\s*\)/i,
  );
  const marks = [
    ...svg.matchAll(
      /<path\b[^>]*\bstyle="[^"]*\bfill:\s*rgb\(\s*(\d+)\s*,\s*(\d+)\s*,\s*(\d+)\s*\)/gi,
    ),
  ];
  if (!background || marks.length !== 2) {
    throw new Error(
      "Brand SVG must contain one colored background and two colored mark paths.",
    );
  }

  const colors = {
    yellow: rgbToHex(background[1], background[2], background[3]),
    navy: rgbToHex(marks[0][1], marks[0][2], marks[0][3]),
    blue: rgbToHex(marks[1][1], marks[1][2], marks[1][3]),
  };
  if (new Set(Object.values(colors)).size !== 3) {
    throw new Error("Brand SVG must contain three distinct base colors.");
  }
  return colors;
}

function themeCss(colors) {
  const darkTheme = `  color-scheme: dark;
  --brand-ink: color-mix(in srgb, white 92%, var(--brand-yellow));
  --brand-muted: color-mix(in srgb, white 68%, var(--brand-navy));
  --brand-paper: color-mix(in srgb, var(--brand-navy) 58%, black);
  --brand-surface: color-mix(in srgb, var(--brand-navy) 72%, black);
  --brand-surface-raised: color-mix(in srgb, var(--brand-navy) 84%, black);
  --brand-primary: var(--brand-blue);
  --brand-primary-strong: color-mix(in srgb, var(--brand-blue) 68%, var(--brand-navy));
  --brand-accent-text: color-mix(in srgb, var(--brand-blue) 48%, white);
  --brand-focus: var(--brand-yellow);
  --brand-primary-soft: color-mix(in srgb, var(--brand-blue) 20%, var(--brand-navy));
  --brand-border: color-mix(in srgb, var(--brand-blue) 28%, var(--brand-navy));
  --brand-highlight: var(--brand-yellow);`;

  return `/* Generated by scripts/generate-brand-assets.mjs. Do not edit directly. */
:root {
  --brand-yellow: ${colors.yellow};
  --brand-navy: ${colors.navy};
  --brand-blue: ${colors.blue};
}

:root,
:root[data-theme="bright"],
:root[data-theme="light"] {
  color-scheme: light;
  --brand-ink: var(--brand-navy);
  --brand-muted: color-mix(in srgb, var(--brand-navy) 66%, white);
  --brand-paper: color-mix(in srgb, var(--brand-yellow) 6%, white);
  --brand-surface: color-mix(in srgb, var(--brand-yellow) 2%, white);
  --brand-surface-raised: white;
  --brand-primary: var(--brand-blue);
  --brand-primary-strong: color-mix(in srgb, var(--brand-blue) 55%, var(--brand-navy));
  --brand-accent-text: var(--brand-navy);
  --brand-focus: var(--brand-blue);
  --brand-primary-soft: color-mix(in srgb, var(--brand-blue) 12%, white);
  --brand-border: color-mix(in srgb, var(--brand-navy) 16%, white);
  --brand-highlight: var(--brand-yellow);
}

@media (prefers-color-scheme: dark) {
  :root:not([data-theme="bright"]):not([data-theme="light"]) {
${darkTheme}
  }
}

:root[data-theme="dark"] {
${darkTheme}
}
`;
}

export function createBrandThemes(colors) {
  const white = "#FFFFFF";
  const black = "#000000";
  return {
    bright: {
      ink: colors.navy,
      muted: mixHex(colors.navy, 66, white),
      paper: mixHex(colors.yellow, 6, white),
      surface: mixHex(colors.yellow, 2, white),
      surfaceRaised: white,
      primary: colors.blue,
      primaryStrong: mixHex(colors.blue, 55, colors.navy),
      primarySoft: mixHex(colors.blue, 12, white),
      border: mixHex(colors.navy, 16, white),
      highlight: colors.yellow,
    },
    dark: {
      ink: mixHex(white, 92, colors.yellow),
      muted: mixHex(white, 68, colors.navy),
      paper: mixHex(colors.navy, 58, black),
      surface: mixHex(colors.navy, 72, black),
      surfaceRaised: mixHex(colors.navy, 84, black),
      primary: colors.blue,
      primaryStrong: mixHex(colors.blue, 68, colors.navy),
      primarySoft: mixHex(colors.blue, 20, colors.navy),
      border: mixHex(colors.blue, 28, colors.navy),
      highlight: colors.yellow,
    },
  };
}

function themeModule(colors) {
  const themes = createBrandThemes(colors);
  return `/* Generated by scripts/generate-brand-assets.mjs. Do not edit directly. */
export const brandBaseColors = ${JSON.stringify(colors, null, 2)} as const;

export const brandThemes = ${JSON.stringify(themes, null, 2)} as const;
`;
}

function transparentMarkSvg(svg) {
  const withoutBackground = svg.replace(/<rect\b[^>]*\/>/i, "");
  if (withoutBackground === svg) {
    throw new Error("Brand SVG background rectangle was not found.");
  }
  return withoutBackground;
}

async function pngFromSvg(svg, size, background, options = {}) {
  const image = sharp(Buffer.from(svg)).resize(size, size, { fit: "contain" });
  if (!options.transparent) {
    image.flatten({ background }).removeAlpha();
  }
  return image.png({ compressionLevel: 9 }).toBuffer();
}

async function adaptiveIconFromSvg(svg) {
  const mark = await pngFromSvg(transparentMarkSvg(svg), 720, "transparent", {
    transparent: true,
  });
  return sharp({
    create: {
      width: 1024,
      height: 1024,
      channels: 4,
      background: { r: 0, g: 0, b: 0, alpha: 0 },
    },
  })
    .composite([{ input: mark, gravity: "centre" }])
    .png({ compressionLevel: 9 })
    .toBuffer();
}

async function createOutputs(svg) {
  const colors = extractBrandColors(svg);
  const icon1024 = await pngFromSvg(svg, 1024, colors.yellow);
  const icon512 = await pngFromSvg(svg, 512, colors.yellow);
  const icon192 = await pngFromSvg(svg, 192, colors.yellow);
  const appleIcon = await pngFromSvg(svg, 180, colors.yellow);
  const favicon = await pngFromSvg(svg, 48, colors.yellow);
  const brandMark = await pngFromSvg(svg, 128, colors.yellow);
  const adaptiveIcon = await adaptiveIconFromSvg(svg);
  const sourceHash = createHash("sha256").update(svg).digest("hex");
  const generatedThemeCss = Buffer.from(
    await prettier.format(themeCss(colors), { parser: "css" }),
  );
  const generatedThemeModule = Buffer.from(
    await prettier.format(themeModule(colors), { parser: "typescript" }),
  );
  const metadata = Buffer.from(
    `${JSON.stringify(
      {
        generatedFrom: "Ressourcen/Flash-n-Flip.svg",
        sha256: sourceHash,
        colors,
      },
      null,
      2,
    )}\n`,
  );

  return new Map([
    ["packages/design/src/brand-theme.css", generatedThemeCss],
    ["packages/design/src/brand-theme.ts", generatedThemeModule],
    ["apps/web/app/icon.svg", Buffer.from(svg)],
    ["apps/web/app/apple-icon.png", appleIcon],
    ["apps/web/public/brand/flash-and-flip.svg", Buffer.from(svg)],
    ["apps/web/public/icons/icon-192.png", icon192],
    ["apps/web/public/icons/icon-512.png", icon512],
    ["apps/web/public/icons/brand-assets.json", metadata],
    ["apps/admin/app/icon.svg", Buffer.from(svg)],
    ["apps/admin/app/apple-icon.png", appleIcon],
    ["apps/admin/public/brand/flash-and-flip.svg", Buffer.from(svg)],
    ["apps/admin/public/icons/icon-192.png", icon192],
    ["apps/admin/public/icons/icon-512.png", icon512],
    ["apps/admin/public/icons/brand-assets.json", metadata],
    ["apps/mobile/assets/icon.png", icon1024],
    ["apps/mobile/assets/adaptive-icon.png", adaptiveIcon],
    ["apps/mobile/assets/splash-icon.png", icon512],
    ["apps/mobile/assets/brand-mark.png", brandMark],
    ["apps/mobile/assets/favicon.png", favicon],
    ["apps/mobile/assets/brand-assets.json", metadata],
  ]);
}

function sameFile(file, expected) {
  return fs.existsSync(file) && fs.readFileSync(file).equals(expected);
}

async function main() {
  const rawSource = fs.readFileSync(sourcePath, "utf8");
  const sanitized = sanitizeBrandSvg(rawSource);
  const formatted = await prettier.format(sanitized, { parser: "html" });
  const outputs = await createOutputs(formatted);
  const mismatches = [];

  for (const [relativePath, content] of outputs) {
    const target = path.join(repositoryRoot, relativePath);
    if (sameFile(target, content)) continue;
    mismatches.push(relativePath);
    if (!checkOnly) {
      fs.mkdirSync(path.dirname(target), { recursive: true });
      fs.writeFileSync(target, content);
    }
  }

  if (checkOnly && mismatches.length > 0) {
    throw new Error(
      `Generated brand assets are stale:\n${mismatches
        .map((item) => `- ${item}`)
        .join("\n")}\nRun: pnpm assets:brand`,
    );
  }
  console.log(
    mismatches.length === 0
      ? "Brand assets are up to date."
      : `Generated ${mismatches.length} brand asset(s).`,
  );
}

const isMain = process.argv[1]
  ? path.resolve(process.argv[1]) === fileURLToPath(import.meta.url)
  : false;
if (isMain) {
  main().catch((cause) => {
    console.error(cause instanceof Error ? cause.message : cause);
    process.exit(1);
  });
}
